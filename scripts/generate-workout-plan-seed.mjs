/**
 * Reads scripts/data/workoutPlan.json and writes supabase/workout_plan_seed.sql
 * with deterministic UUIDs (RFC 4122 v5) for idempotent re-runs.
 * Run: node scripts/generate-workout-plan-seed.mjs
 */
import { createHash } from 'crypto';
import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, '..');

function uuidV5(name, namespaceUuid) {
  const ns = Buffer.from(namespaceUuid.replace(/-/g, ''), 'hex');
  const n = Buffer.from(String(name), 'utf8');
  const hash = createHash('sha1').update(Buffer.concat([ns, n])).digest();
  const bytes = Buffer.from(hash.subarray(0, 16));
  bytes[6] = (bytes[6] & 0x0f) | 0x50;
  bytes[8] = (bytes[8] & 0x3f) | 0x80;
  const h = bytes.toString('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20, 32)}`;
}

const NS = '6ba7b811-9dad-11d1-80b4-00c04fd430c8';

function escSql(str) {
  if (str == null) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

function escArr(arr) {
  if (!arr || arr.length === 0) {
    return 'ARRAY[]::text[]';
  }
  return `ARRAY[${arr.map(s => escSql(s)).join(',')}]`;
}

const raw = JSON.parse(readFileSync(join(root, 'scripts/data/workoutPlan.json'), 'utf8'));
const planMeta = raw.plan;
const schedule = raw.schedule;

const planId = uuidV5('plan:devs-plan', NS);

const exerciseNamesSeen = new Map();
const exerciseRows = [];

for (const day of schedule) {
  for (const ex of day.exercises) {
    if (!exerciseNamesSeen.has(ex.name)) {
      const exId = uuidV5(`exercise:${ex.name}`, NS);
      exerciseNamesSeen.set(ex.name, exId);
      exerciseRows.push({
        id: exId,
        name: ex.name,
        equipment: ex.equipment,
        type: ex.type,
        muscle_primary: ex.muscle_primary,
        muscle_secondary: ex.muscle_secondary ?? [],
        notes: ex.note ?? null,
      });
    }
  }
}

const dayRows = [];
const planExerciseRows = [];

for (const day of schedule) {
  const dayId = uuidV5(`planday:${planId}:${day.day}`, NS);
  dayRows.push({
    id: dayId,
    day: day.day,
    type: day.type,
    focus: day.focus,
    duration_minutes: day.duration_minutes,
    warmup: day.warmup,
    cardio_title: day.cardio_finisher?.type ?? '',
    cardio_duration_minutes: day.cardio_finisher?.duration_minutes ?? null,
    cardio_instructions: day.cardio_finisher?.parameters ?? '',
  });

  for (const ex of day.exercises) {
    const exerciseId = exerciseNamesSeen.get(ex.name);
    const peId = uuidV5(`planex:${dayId}:${ex.order}:${ex.name}`, NS);
    planExerciseRows.push({
      id: peId,
      plan_day_id: dayId,
      exercise_id: exerciseId,
      sort_order: ex.order,
      sets: ex.sets,
      reps: ex.reps,
    });
  }
}

let sql = `-- Generated by scripts/generate-workout-plan-seed.mjs — do not edit by hand; re-run the script after JSON changes.
-- Seed: Dev's Plan + exercises + plan_days + plan_exercises (from legacy workoutPlan.json)

begin;

`;

sql += `insert into public.plans (id, name, goal, level, days_per_week) values (
  '${planId}'::uuid,
  ${escSql("Dev's Plan")},
  ${escSql(planMeta.goal)},
  ${escSql(planMeta.level)},
  ${planMeta.days_per_week}
) on conflict (id) do update set
  name = excluded.name,
  goal = excluded.goal,
  level = excluded.level,
  days_per_week = excluded.days_per_week;

`;

for (const e of exerciseRows) {
  sql += `insert into public.exercises (id, name, equipment, type, muscle_primary, muscle_secondary, notes) values (
  '${e.id}'::uuid,
  ${escSql(e.name)},
  ${escSql(e.equipment)},
  ${escSql(e.type)},
  ${escSql(e.muscle_primary)},
  ${escArr(e.muscle_secondary)},
  ${e.notes != null ? escSql(e.notes) : 'NULL'}
) on conflict (id) do update set
  name = excluded.name,
  equipment = excluded.equipment,
  type = excluded.type,
  muscle_primary = excluded.muscle_primary,
  muscle_secondary = excluded.muscle_secondary,
  notes = excluded.notes;

`;
}

for (const d of dayRows) {
  sql += `insert into public.plan_days (
  id, plan_id, day, type, focus, duration_minutes,
  warmup, cardio_title, cardio_duration_minutes, cardio_instructions
) values (
  '${d.id}'::uuid,
  '${planId}'::uuid,
  ${escSql(d.day)},
  ${escSql(d.type)},
  ${escSql(d.focus)},
  ${d.duration_minutes},
  ${escSql(d.warmup)},
  ${escSql(d.cardio_title)},
  ${d.cardio_duration_minutes != null ? d.cardio_duration_minutes : 'NULL'},
  ${escSql(d.cardio_instructions)}
) on conflict (plan_id, day) do update set
  type = excluded.type,
  focus = excluded.focus,
  duration_minutes = excluded.duration_minutes,
  warmup = excluded.warmup,
  cardio_title = excluded.cardio_title,
  cardio_duration_minutes = excluded.cardio_duration_minutes,
  cardio_instructions = excluded.cardio_instructions;

`;
}

for (const pe of planExerciseRows) {
  sql += `insert into public.plan_exercises (id, plan_day_id, exercise_id, sort_order, sets, reps) values (
  '${pe.id}'::uuid,
  '${pe.plan_day_id}'::uuid,
  '${pe.exercise_id}'::uuid,
  ${pe.sort_order},
  ${pe.sets},
  ${escSql(pe.reps)}
) on conflict (id) do update set
  sort_order = excluded.sort_order,
  sets = excluded.sets,
  reps = excluded.reps;

`;
}

sql += `commit;
`;

const outPath = join(root, 'supabase/workout_plan_seed.sql');
writeFileSync(outPath, sql, 'utf8');
console.log(`Wrote ${outPath} (${exerciseRows.length} exercises, ${dayRows.length} days, ${planExerciseRows.length} plan_exercises)`);
